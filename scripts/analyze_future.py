#!/usr/bin/env python3
"""Tables + figure for the future-work extensions (results/future/future.csv, from
`python scripts/bench.py --exp future --gate-every 0 --out results/future`).

  A  cost-weighted MPI partitioning (--partition cost) vs equal body counts
  B  controller auto mode (--balanced auto) vs the fixed alternatives
  C  parallel Morton sort + tree build

Writes results/future/summary.md and results/future/future.png (medians over repetitions).
Usage: python scripts/analyze_future.py [--dir results/future]
"""
import argparse
import csv
import os
import statistics
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import RESULTS  # noqa: E402


def load(path):
    runs = defaultdict(list)
    with open(path, newline="") as f:
        for r in csv.DictReader(f):
            runs[r["label"].split(":")[1]].append(r)
    return runs


def med(rows, key):
    return statistics.median(float(r[key]) for r in rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=os.path.join(RESULTS, "future"))
    d = ap.parse_args().dir
    runs = load(os.path.join(d, "future.csv"))
    reps = max(len(v) for v in runs.values())
    out = ["# Future-work extensions: benchmark summary", "",
           f"Generated by `python scripts/analyze_future.py` from `future.csv` (median of {reps} repetitions).",
           "Machine: AMD Ryzen 7 7730U (8 cores / 16 threads, all cores identical), Windows 11, "
           "MinGW-w64 GCC 15.2 (-O3 -march=native), MS-MPI 10.1, no CUDA GPU.", ""]

    # A: partitioning ---------------------------------------------------------------------------
    out += ["## A. Cost-weighted MPI partitioning (N = 65536, 100 steps)", "",
            "| input | ranks x threads | schedule | equal: time [s] | cost: time [s] | change | "
            "rank imbalance equal -> cost | comm equal / cost [s] |", "|---|---|---|---|---|---|---|---|"]
    part = []
    for key in sorted(k for k in runs if k.startswith("part_") and k.endswith("_equal")):
        ck = key[:-len("equal")] + "cost"
        if ck not in runs:
            continue
        _, ic, pr, tr, s, _ = key.split("_")
        te, tc = med(runs[key], "t_total"), med(runs[ck], "t_total")
        le, lc = med(runs[key], "lam_rank_mean"), med(runs[ck], "lam_rank_mean")
        part.append((f"{ic} {pr[1:]}x{tr[1:]} {s}", te, tc, le, lc))
        out.append(f"| {ic} | {pr[1:]} x {tr[1:]} | {s} | {te:.2f} | {tc:.2f} | {100 * (tc / te - 1):+.1f} % | "
                   f"{le:.3f} -> {lc:.3f} | {med(runs[key], 't_comm'):.2f} / {med(runs[ck], 't_comm'):.2f} |")

    # B: controller auto ------------------------------------------------------------------------
    out += ["", "## B. Controller auto mode (N = 65536, 8 threads, 150 steps)", "",
            "Time relative to static (< 1 is faster); `adaptive-auto` tries dynamic(8), dynamic(64) and "
            "guided(8) for one k-step window each after switching away from static, then keeps the fastest.", "",
            "| input | static [s] | guided | adaptive (dynamic) | adaptive (auto) | auto picked |",
            "|---|---|---|---|---|---|"]
    auto = []
    for ic in ["uniform", "plummer", "collide", "collapse"]:
        k = f"auto_{ic}_"
        if k + "static" not in runs:
            continue
        ts = med(runs[k + "static"], "t_total")
        rel = {v: med(runs[k + v], "t_total") / ts for v in ("guided", "adaptive-dyn", "adaptive-auto") if k + v in runs}
        picks = sorted({f"{r['chosen']}({r['chosen_chunk']})" if r["chosen"] != "none" else "stayed static"
                        for r in runs.get(k + "adaptive-auto", [])})
        auto.append((ic, rel))
        out.append(f"| {ic} | {ts:.2f} | {rel.get('guided', float('nan')):.3f} | "
                   f"{rel.get('adaptive-dyn', float('nan')):.3f} | {rel.get('adaptive-auto', float('nan')):.3f} | "
                   f"{', '.join(picks)} |")

    # C: parallel build ---------------------------------------------------------------------------
    out += ["", "## C. Parallel Morton sort + tree build (Plummer, 20 steps)", "",
            "| N | sort 1 thread [ms/step] | sort 8 threads | speedup | tree 1 thread [ms/step] | tree 8 threads | speedup |",
            "|---|---|---|---|---|---|---|"]
    build = []
    for n in (65536, 262144):
        a, b = runs.get(f"build_n{n}_T1"), runs.get(f"build_n{n}_T8")
        if not a or not b:
            continue
        steps = float(a[0]["steps"])
        s1, s8 = 1e3 * med(a, "t_sort") / steps, 1e3 * med(b, "t_sort") / steps
        b1, b8 = 1e3 * med(a, "t_build") / steps, 1e3 * med(b, "t_build") / steps
        build.append((n, s1, s8, b1, b8))
        out.append(f"| {n} | {s1:.2f} | {s8:.2f} | {s1 / s8:.2f}x | {b1:.2f} | {b8:.2f} | {b1 / b8:.2f}x |")

    with open(os.path.join(d, "summary.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not installed - figure skipped")
        return
    fig, ax = plt.subplots(1, 3, figsize=(15, 4.5))
    if part:
        x = range(len(part))
        ax[0].bar([i - 0.2 for i in x], [p[3] for p in part], 0.4, label="equal counts")
        ax[0].bar([i + 0.2 for i in x], [p[4] for p in part], 0.4, label="cost-weighted")
        ax[0].set_xticks(list(x))
        ax[0].set_xticklabels([p[0] for p in part], fontsize=7, rotation=45, ha="right")
        ax[0].set_ylabel("rank imbalance (force phase)")
        ax[0].set_title("A. MPI partitioning")
        ax[0].legend()
    if auto:
        x = range(len(auto))
        for j, (v, lab) in enumerate([("guided", "guided"), ("adaptive-dyn", "adaptive -> dynamic"),
                                      ("adaptive-auto", "adaptive -> auto")]):
            ax[1].bar([i + (j - 1) * 0.27 for i in x], [a[1].get(v, 0) for a in auto], 0.27, label=lab)
        ax[1].axhline(1.0, color="k", lw=0.8)
        ax[1].set_xticks(list(x))
        ax[1].set_xticklabels([a[0] for a in auto])
        ax[1].set_ylabel("time / static")
        ax[1].set_title("B. Controller auto mode (8 threads)")
        ax[1].legend(fontsize=8, loc="lower center")
    if build:
        x = range(len(build))
        ax[2].bar([i - 0.2 for i in x], [b[1] / b[2] for b in build], 0.4, label="Morton sort")
        ax[2].bar([i + 0.2 for i in x], [b[3] / b[4] for b in build], 0.4, label="tree build")
        ax[2].set_xticks(list(x))
        ax[2].set_xticklabels([f"N = {b[0]}" for b in build])
        ax[2].set_ylabel("speedup, 8 threads vs 1")
        ax[2].set_title("C. Parallel sort + tree build")
        ax[2].legend()
    fig.tight_layout()
    fig.savefig(os.path.join(d, "future.png"), dpi=130)
    print("wrote", os.path.join(d, "future.png"))


if __name__ == "__main__":
    main()
