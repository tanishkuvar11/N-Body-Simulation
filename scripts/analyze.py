#!/usr/bin/env python3
"""Turn results/*.csv into figures (results/figures/*.png) and tables (results/summary.md).

All timings are medians over the repetitions.  Speedup S(p) = T(1)/T(p) with T(1) the
single-thread static run (same input, same N); efficiency E(p) = S(p)/p.
Usage: python scripts/analyze.py
"""
import csv
import os
import statistics as st
import sys
from collections import defaultdict

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import RESULTS  # noqa: E402

FIG = os.path.join(RESULTS, "figures")
SCHEDS = ["static", "dynamic", "guided", "adaptive"]
ICS = ["uniform", "plummer", "collide", "collapse"]
IC_TITLE = {"uniform": "Uniform (balanced control)", "plummer": "Plummer sphere",
            "collide": "Colliding clusters", "collapse": "Cold collapse (clustering develops)"}
# reference categorical palette, slots 1-4, plus a distinct marker per series
COL = {"static": "#2a78d6", "dynamic": "#eb6834", "guided": "#1baf7a", "adaptive": "#eda100"}
MRK = {"static": "o", "dynamic": "s", "guided": "^", "adaptive": "D"}
INK, INK2, GRID = "#0b0b0b", "#52514e", "#e4e3df"

plt.rcParams.update({
    "font.size": 9, "axes.edgecolor": INK2, "axes.labelcolor": INK, "xtick.color": INK2, "ytick.color": INK2,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6, "axes.spines.top": False,
    "axes.spines.right": False, "legend.frameon": False, "figure.dpi": 150, "savefig.bbox": "tight",
    "lines.linewidth": 2, "lines.markersize": 5,
})


def load(name):
    p = os.path.join(RESULTS, f"{name}.csv")
    if not os.path.isfile(p):
        return []
    with open(p, newline="") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["key"] = r["label"].split(":")[1]
    return rows


def med(rows, field="t_total"):
    return st.median(float(r[field]) for r in rows) if rows else float("nan")


def group(rows, *fields):
    g = defaultdict(list)
    for r in rows:
        g[tuple(r[f] for f in fields)].append(r)
    return g


def save(fig, name):
    os.makedirs(FIG, exist_ok=True)
    fig.savefig(os.path.join(FIG, name))
    plt.close(fig)
    print("  wrote figures/" + name)


md = ["# Benchmark summary", "",
      "Generated by `python scripts/analyze.py` from `results/*.csv` (medians over repetitions).",
      "Machine: Intel Core i7-14700HX (8 P-cores + 12 E-cores, 28 logical CPUs), NVIDIA RTX 4060 Laptop GPU, "
      "Windows 11, MinGW-w64 GCC 15.1 (-O3 -march=native), MS-MPI 10.1, CUDA via NVRTC 12.9.", ""]


# ------------------------------------------------------------------ schedule experiment
def analyze_sched():
    rows = load("sched")
    if not rows:
        return
    for r in rows:
        r["n"], r["threads"] = int(r["n"]), int(r["threads"])
    g = group(rows, "ic", "n", "threads", "sched")
    ns = sorted({r["n"] for r in rows})
    ts = sorted({r["threads"] for r in rows})

    def T(ic, n, t, s):
        return med(g.get((ic, n, t, s), []))

    md.extend(["## 1. OpenMP schedule comparison (1 MPI rank, threads pinned to P-cores, 150 steps)", ""])
    for n in ns:
        md.append(f"### N = {n}: total time [s] and speedup vs 1 thread")
        md.append("")
        md.append("| input | threads | " + " | ".join(SCHEDS) + " | best | adaptive vs static |")
        md.append("|---|---|" + "---|" * (len(SCHEDS) + 2))
        for ic in ICS:
            t1 = T(ic, n, 1, "static")
            md.append(f"| {ic} | 1 | {t1:.2f} (1.00x) | | | | | |")
            for t in ts:
                if t == 1:
                    continue
                vals = {s: T(ic, n, t, s) for s in SCHEDS}
                best = min(vals, key=vals.get)
                cells = [f"{vals[s]:.2f} ({t1 / vals[s]:.2f}x)" for s in SCHEDS]
                gain = (vals["static"] - vals["adaptive"]) / vals["static"] * 100
                md.append(f"| {ic} | {t} | " + " | ".join(cells) + f" | {best} | {gain:+.1f} % |")
        md.append("")

    # speedup + efficiency figures for the largest N
    for n in ns:
        fig, axes = plt.subplots(2, 4, figsize=(13, 6), sharex=True)
        for j, ic in enumerate(ICS):
            t1 = T(ic, n, 1, "static")
            for s in SCHEDS:
                xs = [t for t in ts if (t == 1) or (ic, n, t, s) in g]
                sp = [t1 / (T(ic, n, t, "static") if t == 1 else T(ic, n, t, s)) for t in xs]
                axes[0, j].plot(xs, sp, color=COL[s], marker=MRK[s], label=s)
                axes[1, j].plot(xs, [a / t for a, t in zip(sp, xs)], color=COL[s], marker=MRK[s], label=s)
            axes[0, j].plot(ts, ts, color=INK2, lw=1, ls="--", label="ideal")
            axes[0, j].set_title(IC_TITLE[ic], color=INK, fontsize=9)
            axes[1, j].set_xlabel("OpenMP threads")
            axes[1, j].set_ylim(0, 1.1)
            for a in axes[:, j]:
                a.set_xticks(ts)
        axes[0, 0].set_ylabel("speedup  T(1)/T(p)")
        axes[1, 0].set_ylabel("efficiency  S(p)/p")
        axes[0, 0].legend(loc="upper left")
        fig.suptitle(f"Strong scaling of the Barnes-Hut force loop, N = {n} (median of repetitions)", color=INK)
        save(fig, f"speedup_n{n}.png")

    # headline: time relative to static at max threads for each N
    tmax = max(ts)
    fig, axes = plt.subplots(1, len(ns), figsize=(4.2 * len(ns), 3.4), sharey=True)
    axes = axes if len(ns) > 1 else [axes]
    for a, n in zip(axes, ns):
        w = 0.2
        for k, s in enumerate(SCHEDS):
            ys = [T(ic, n, tmax, s) / T(ic, n, tmax, "static") for ic in ICS]
            a.bar([i + (k - 1.5) * w for i in range(len(ICS))], ys, w * 0.9, color=COL[s], label=s,
                  edgecolor="white", linewidth=0.5)
        a.axhline(1.0, color=INK2, lw=1)
        a.set_xticks(range(len(ICS)))
        a.set_xticklabels(ICS)
        a.set_title(f"N = {n}, {tmax} threads", color=INK, fontsize=9)
        a.set_ylim(0.6, 1.5)
    axes[0].set_ylabel("run time relative to static (lower is better)")
    axes[0].legend(ncol=2, loc="upper left")
    save(fig, "relative_to_static.png")


def analyze_traces():
    tdir = os.path.join(RESULTS, "traces")
    if not os.path.isdir(tdir):
        return
    files = [f for f in os.listdir(tdir) if f.startswith("sched_trace_")]
    if not files:
        return
    n = max(int(f.split("_n")[1].split("_")[0]) for f in files)
    tmax = max(int(f.split("_T")[1].split("_")[0]) for f in files)

    def read(ic, s):
        p = os.path.join(tdir, f"sched_trace_{ic}_n{n}_T{tmax}_{s}.csv")
        if not os.path.isfile(p):
            return None
        with open(p, newline="") as f:
            return list(csv.DictReader(f))

    fig, axes = plt.subplots(2, 4, figsize=(13, 5.6), sharex=True)
    for j, ic in enumerate(ICS):
        ts_, ad = read(ic, "static"), read(ic, "adaptive")
        ax, bx = axes[0, j], axes[1, j]
        if ts_:
            x = [float(r["time"]) for r in ts_][1:]
            ax.plot(x, [float(r["lam_time"]) for r in ts_][1:], color=COL["static"], lw=1, label="measured (static run)")
            ax.plot(x, [float(r["lam_static_work"]) for r in ts_][1:], color=INK, lw=1.5, ls="--",
                    label="workload (interaction counts)")
        if ad:
            chk = [r for r in ad if r["lam_check"]]
            ax.plot([float(r["time"]) for r in chk], [float(r["lam_check"]) for r in chk], color=COL["adaptive"],
                    marker="D", ms=3, lw=0, label="controller check (adaptive run)")
            x = [float(r["time"]) for r in ad][1:]
            dyn = [r["policy"] == "dynamic" for r in ad][1:]
            for xi, d in zip(x, dyn):
                if d:
                    bx.axvspan(xi - 0.005, xi + 0.005, color=COL["dynamic"], alpha=0.12, lw=0)
            bx.plot(x, [float(r["t_force"]) * 1e3 for r in ad][1:], color=COL["adaptive"], lw=1, label="adaptive")
        if ts_:
            bx.plot([float(r["time"]) for r in ts_][1:], [float(r["t_force"]) * 1e3 for r in ts_][1:],
                    color=COL["static"], lw=1, label="static")
        dy = read(ic, "dynamic")
        if dy:
            bx.plot([float(r["time"]) for r in dy][1:], [float(r["t_force"]) * 1e3 for r in dy][1:],
                    color=COL["dynamic"], lw=1, label="dynamic")
        ax.set_title(IC_TITLE[ic], color=INK, fontsize=9)
        ax.axhline(0.15, color=INK2, lw=0.8, ls=":")
        ax.axhline(0.05, color=INK2, lw=0.8, ls=":")
        bx.set_xlabel("simulation time")
    axes[0, 0].set_ylabel("imbalance  lambda = max/mean - 1")
    axes[1, 0].set_ylabel("force-loop time per step [ms]")
    axes[0, 0].legend(fontsize=7, loc="upper left")
    axes[1, 0].legend(fontsize=7, loc="upper left")
    fig.suptitle(f"Load imbalance over time and controller decisions (N = {n}, {tmax} threads; shaded = adaptive "
                 f"run using dynamic; dotted = thresholds low/high)", color=INK, fontsize=9)
    save(fig, "imbalance_traces.png")


