def analyze_mpi():
    rows = load("mpi")
    if not rows:
        return
    g = group(rows, "ic", "ranks", "threads", "sched")
    combos = sorted({(int(r["ranks"]), int(r["threads"])) for r in rows}, key=lambda c: (c[0] * c[1], c[0]))
    md.extend(["## 2. Hybrid MPI x OpenMP (N = 65536, 100 steps)", "",
               "Up to 8 workers: one per P-core; 16 workers: both SMT threads of the 8 P-cores.", "",
               "Speedups are given against two single-thread baselines: the 1 x 1 run of this experiment, and the",
               "single-thread run of the schedule experiment (scaled to 100 steps).  They differ because the CPU's",
               "single-core turbo was ~1.5x lower during this (later) session while multi-core speed was unchanged;",
               "the second, faster baseline is the conservative one.  Configurations with the same number of",
               "workers are directly comparable via the time columns.", "",
               "| input | ranks x threads | static [s] | dynamic [s] | adaptive [s] | speedup vs 1x1 (this run) | "
               "speedup vs schedule-exp. T1 | rank imbalance (static) | comm [s] |",
               "|---|---|---|---|---|---|---|---|---|"])
    sched_rows = load("sched")
    ics = [ic for ic in ["uniform", "collide"] if any(r["ic"] == ic for r in rows)]
    fig, axes = plt.subplots(1, len(ics), figsize=(6.2 * len(ics), 3.6), sharey=True)
    axes = axes if len(ics) > 1 else [axes]
    for a, ic in zip(axes, ics):
        t11 = med(g.get((ic, "1", "1", "static"), []))
        steps = int(next(r for r in rows if r["ic"] == ic)["steps"])
        nn = next(r for r in rows if r["ic"] == ic)["n"]
        st1 = [r for r in sched_rows if r["key"] == f"{ic}_n{nn}_T1_static"]
        t1s = med(st1) * steps / int(st1[0]["steps"]) if st1 else float("nan")
        labels, w = [], 0.27
        for i, (p, t) in enumerate(combos):
            vals = {}
            for s in ["static", "dynamic", "adaptive"]:
                rr = g.get((ic, str(p), str(t), s), [])
                if rr:
                    vals[s] = med(rr)
            st_rows = g.get((ic, str(p), str(t), "static"), [])
            best = min(vals.values())
            md.append(f"| {ic} | {p} x {t} | " + " | ".join(f"{vals[s]:.2f}" if s in vals else "-" for s in
                      ["static", "dynamic", "adaptive"]) + f" | {t11 / best:.2f}x | {t1s / best:.2f}x | {med(st_rows, 'lam_rank_mean'):.3f} |"
                      f" {med(st_rows, 't_comm'):.3f} |")
            for k, s in enumerate(["static", "dynamic", "adaptive"]):
                if s in vals:
                    a.bar(i + (k - 1) * w, t1s / vals[s], w * 0.9, color=COL[s], edgecolor="white", linewidth=0.5,
                          label=s if i == len(combos) - 1 else None)
            labels.append(f"{p}x{t}")
        a.set_xticks(range(len(combos)))
        a.set_xticklabels(labels)
        a.set_xlabel("MPI ranks x OpenMP threads")
        a.set_title(IC_TITLE[ic], color=INK, fontsize=9)
    axes[0].set_ylabel("speedup vs single thread (schedule experiment)")
    axes[0].legend(loc="upper left")
    save(fig, "mpi_hybrid.png")
    md.append("")


# ------------------------------------------------------------------ GPU
def analyze_gpu():
    rows = load("gpu")
    if not rows:
        return
    g = group(rows, "key")

    def m(key, field="t_step"):
        return med([r for r in rows if r["key"] == key], field)

    ns = sorted({int(r["n"]) for r in rows if r["key"].startswith("direct_")})
    md.extend(["## 3. CUDA kernels", "", "### Direct summation, time per step [ms] (CPU: 8 pinned threads)", "",
               "| N | CPU direct | GPU double | GPU float | GPU float speedup vs CPU | float rms error |",
               "|---|---|---|---|---|---|"])
    series = {"CPU direct (8 threads, fp64)": "direct_cpu_n{}", "GPU tiled kernel, fp64": "direct_gpu_double_n{}",
              "GPU tiled kernel, fp32": "direct_gpu_float_n{}"}
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.8))
    for (lab, kf), c, mk in zip(series.items(), ["#2a78d6", "#eb6834", "#1baf7a"], ["o", "s", "^"]):
        axes[0].plot(ns, [m(kf.format(n)) * 1e3 for n in ns], color=c, marker=mk, label=lab)
    for n in ns:
        cpu, gd, gf = (m(f"direct_cpu_n{n}"), m(f"direct_gpu_double_n{n}"), m(f"direct_gpu_float_n{n}"))
        md.append(f"| {n} | {cpu * 1e3:.2f} | {gd * 1e3:.2f} | {gf * 1e3:.2f} | {cpu / gf:.1f}x | "
                  f"{m(f'direct_gpu_float_n{n}', 'verify_rms'):.1e} |")
    axes[0].set_xscale("log", base=2)
    axes[0].set_yscale("log")
    axes[0].set_xlabel("N")
    axes[0].set_ylabel("time per step [ms]")
    axes[0].set_title("O(N^2) direct summation", color=INK, fontsize=9)
    axes[0].legend()

    bn = sorted({int(r["n"]) for r in rows if r["key"].startswith("bh_")})
    md.extend(["", "### Barnes-Hut: CPU tree code vs BH+GPU hybrid, time per step [ms]", "",
               "| N | CPU leaf 8 | CPU leaf 16 | hybrid fp64 leaf 32 | hybrid fp32 leaf 256 | hybrid fp32 speedup vs best CPU | rms force error (CPU leaf 16 / hybrid fp32) |",
               "|---|---|---|---|---|---|---|"])
    bseries = [("CPU, leaf 8", "bh_cpu_leaf8_n{}"), ("CPU, leaf 16", "bh_cpu_leaf16_n{}"),
               ("hybrid fp64, leaf 32", "bh_gpu_double_leaf32_n{}"), ("hybrid fp32, leaf 256", "bh_gpu_float_leaf256_n{}")]
    w = 0.2
    for k, ((lab, kf), c) in enumerate(zip(bseries, ["#2a78d6", "#6250d6", "#eb6834", "#1baf7a"])):
        axes[1].bar([i + (k - 1.5) * w for i in range(len(bn))], [m(kf.format(n)) * 1e3 for n in bn], w * 0.9,
                    color=c, edgecolor="white", linewidth=0.5, label=lab)
    for n in bn:
        v = [m(kf.format(n)) for _, kf in bseries]
        md.append(f"| {n} | " + " | ".join(f"{x * 1e3:.2f}" for x in v) + f" | {min(v[0], v[1]) / v[3]:.2f}x | "
                  f"{m(f'bh_cpu_leaf16_n{n}', 'verify_rms'):.2e} / {m(f'bh_gpu_float_leaf256_n{n}', 'verify_rms'):.2e} |")
    axes[1].set_xticks(range(len(bn)))
    axes[1].set_xticklabels([str(n) for n in bn])
    axes[1].set_xlabel("N")
    axes[1].set_ylabel("time per step [ms]")
    axes[1].set_yscale("log")
    axes[1].set_title("Barnes-Hut (theta = 0.5), 8 CPU threads", color=INK, fontsize=9)
    axes[1].legend(fontsize=7)
    save(fig, "gpu.png")
    md.append("")


# ------------------------------------------------------------------ controller sensitivity
def analyze_ctl():
    rows = load("ctl")
    if not rows:
        return
    g = group(rows, "key")
    md.extend(["## 4. Controller sensitivity (cold collapse, N = 65536, 8 threads)", "",
               "| setting | total [s] | switches | fraction of steps dynamic |", "|---|---|---|---|"])
    for key in ["k1", "k5", "k10", "k20", "high0.1", "high0.25", "high0.4"]:
        rr = g.get((key,), [])
        if rr:
            lab = {"k1": "k = 1", "k5": "k = 5 (default, high 0.15)", "k10": "k = 10", "k20": "k = 20",
                   "high0.1": "high 0.10 / low 0.033", "high0.25": "high 0.25 / low 0.083",
                   "high0.4": "high 0.40 / low 0.133"}[key]
            md.append(f"| {lab} | {med(rr):.2f} | {med(rr, 'switches'):.0f} | {med(rr, 'frac_dynamic'):.2f} |")
    md.extend(["", "Dynamic chunk size on colliding clusters (N = 65536, 8 threads):", "",
               "| schedule | total [s] |", "|---|---|"])
    for key, lab in [("collide_static", "static"), ("collide_dynamic_c1", "dynamic, chunk 1"),
                     ("collide_dynamic_c8", "dynamic, chunk 8"), ("collide_dynamic_c64", "dynamic, chunk 64"),
                     ("collide_dynamic_c512", "dynamic, chunk 512")]:
        rr = g.get((key,), [])
        if rr:
            md.append(f"| {lab} | {med(rr):.2f} |")
    md.append("")


def analyze_small():
    rows = load("small")
    if not rows:
        return
    g = group(rows, "key")
    md.extend(["## 5. Scheduling overhead at small N (uniform input, 8 threads, 400 steps)", "",
               "| N | static [s] | dynamic chunk 1 [s] | dynamic chunk 8 [s] | adaptive [s] |", "|---|---|---|---|---|"])
    for n in (1024, 2048):
        vals = [med(g.get((f"n{n}_{k}",), [])) for k in ("static", "dynamic_c1", "dynamic_c8", "adaptive")]
